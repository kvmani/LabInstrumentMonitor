"""Documented test path for long-history fixtures (``labmon-server load-fixture``).

Development and test databases only. The fixture is generated by the same simulator code as
live acquisition and written with PostgreSQL ``COPY`` (millions of rows in about a minute)
instead of through HTTP batches. Original event times are kept. The fixture uses its own
collector (``col-fixture``) whose assignment covers only the fixture window, so the instrument
never looks live. Identity-ledger rows are not written: fixture identities are not replayable
by any collector. Every touched minute is queued for the rollup worker.
"""

from __future__ import annotations

import logging
from datetime import UTC, datetime, timedelta
from typing import Any

from sqlalchemy import Engine, insert, select, text

from labmon.contracts.envelope import EventType, sha256_hex
from labmon.server.bootstrap import (
    DEMO_LAB,
    InstrumentSeed,
    ensure_collector,
    ensure_instrument,
    ensure_lab,
)
from labmon.server.models import AcquisitionEvent, CollectorAssignment, Sample
from labmon.sim.base import SourceUnavailable
from labmon.sim.fixtures import FIXTURES

log = logging.getLogger(__name__)

_COLUMNS = (
    "collector_id",
    "spool_epoch",
    "seq",
    "channel_id",
    "instrument_id",
    "profile_revision_id",
    "frame_id",
    "value_num",
    "value_int",
    "raw",
    "quality",
    "quality_reason",
    "source_time_meaning",
    "capture_time",
    "receive_time",
    "event_time",
    "event_time_source",
    "clock_confidence",
    "simulated",
    "receipt_id",
)


class FixtureError(Exception):
    pass


def load_fixture(
    engine: Engine,
    key: str,
    channels: tuple[str, ...] | None = None,
    lab: tuple[str, str] = DEMO_LAB,
) -> dict[str, Any]:
    fx = FIXTURES.get(key)
    if fx is None:
        raise FixtureError(f"unknown fixture {key!r}; known: {sorted(FIXTURES)}")
    source = fx.source()
    keys = channels or tuple(c.key for c in source.profile.channels)
    unknown = set(keys) - {c.key for c in source.profile.channels}
    if unknown:
        raise FixtureError(f"unknown channels {sorted(unknown)}")
    seed = InstrumentSeed(
        fx.instrument_id,
        fx.name,
        source.profile.key,
        fx.seed,
        asset_id="SIM-FH",
        location="historical fixture",
    )
    loaded_at = datetime.now(UTC)
    with engine.begin() as c:
        ensure_lab(c, *lab)
        rev = ensure_instrument(c, lab[0], seed, actor=f"fixture:{key}")
        ensure_collector(c, fx.collector_id, lab[0], "Fixture loader (not a live collector)")
        if c.execute(
            select(Sample.seq).where(Sample.instrument_id == fx.instrument_id).limit(1)
        ).first():
            raise FixtureError(f"fixture {key} is already loaded")
        c.execute(
            insert(CollectorAssignment).values(
                collector_id=fx.collector_id,
                instrument_id=fx.instrument_id,
                valid_from=fx.start,
                valid_to=fx.end,
                reason=f"fixture {key}",
            )
        )
        receipt = c.execute(
            text(
                "INSERT INTO batch_receipt (collector_id, batch_id, payload_digest,"
                " protocol_version,"
                " outcome, record_count, accepted, duplicates, rejected, received_at) VALUES"
                " (:c, :b, :d, 1, 'committed', 0, 0, 0, '[]', :t) RETURNING id"
            ),
            {
                "c": fx.collector_id,
                "b": sha256_hex(f"fixture:{key}")[:32],
                "d": f"fixture:{key}",
                "t": loaded_at,
            },
        ).scalar_one()

    profile = source.profile
    dtypes = {c.key: c.data_type.value for c in profile.channels}
    seq = 0
    rows = 0
    start_ms = int(fx.start.timestamp() * 1000)
    raw = engine.raw_connection()
    try:
        pg = raw.driver_connection
        assert pg is not None
        copy_sql = f"COPY sample ({', '.join(_COLUMNS)}) FROM STDIN"  # noqa: S608 - fixed
        for day in range(fx.days):  # one transaction per day: bounded and resumable
            with pg.cursor() as cur:
                # the API's 30 s statement timeout protects requests, not bulk test loads
                cur.execute("SET LOCAL statement_timeout = 0")
                with cur.copy(copy_sql) as cp:
                    for i in range(day * 86400, (day + 1) * 86400):
                        t_ms = start_ms + i * 1000
                        try:
                            reading = source.read(t_ms)
                        except SourceUnavailable:
                            continue
                        at = datetime.fromtimestamp(t_ms / 1000, UTC)
                        for ch in reading.channels:
                            if ch.key not in keys:
                                continue
                            seq += 1
                            is_enum = dtypes[ch.key] == "enum"
                            reason = None if ch.quality_reason is None else ch.quality_reason.value
                            cp.write_row(
                                (
                                    fx.collector_id,
                                    1,
                                    seq,
                                    f"{fx.instrument_id}.{ch.key}",
                                    fx.instrument_id,
                                    rev,
                                    f"{fx.instrument_id}:{t_ms}",
                                    None if is_enum else ch.value,
                                    ch.value if is_enum else None,
                                    ch.raw,
                                    ch.quality.value,
                                    reason,
                                    "absent",
                                    at,
                                    loaded_at,
                                    at,
                                    "capture",
                                    "trusted",
                                    True,
                                    receipt,
                                )
                            )
                            rows += 1
            pg.commit()
            log.info("fixture %s: day %d/%d loaded", key, day + 1, fx.days)
    finally:
        raw.close()

    with engine.begin() as c:
        events = [
            (fx.start, EventType.ACQUISITION_STARTED, {"mode": "fixture_replay", "fixture": key}),
            (fx.dropout_start, EventType.SOURCE_UNAVAILABLE, {"reason": "scripted dropout"}),
            (
                fx.dropout_end,
                EventType.SOURCE_RECOVERED,
                {"unavailable_since": fx.dropout_start.isoformat()},
            ),
        ]
        c.execute(
            insert(AcquisitionEvent),
            [
                {
                    "collector_id": fx.collector_id,
                    "spool_epoch": 1,
                    "seq": seq + 1 + n,
                    "instrument_id": fx.instrument_id,
                    "profile_revision_id": rev,
                    "event_type": et.value,
                    "detail": detail,
                    "capture_time": at,
                    "receive_time": loaded_at,
                    "clock_confidence": "trusted",
                    "simulated": True,
                    "receipt_id": receipt,
                }
                for n, (at, et, detail) in enumerate(events)
            ],
        )
        c.execute(
            text(
                "INSERT INTO rollup_dirty (channel_id, bucket, revision, marked_at)"
                " SELECT channel_id, date_bin(interval '1 minute', event_time,"
                " timestamptz '2000-01-01 00:00:00+00'), 1, :t FROM sample"
                " WHERE instrument_id = :i GROUP BY 1, 2"
                " ON CONFLICT (channel_id, bucket)"
                " DO UPDATE SET revision = rollup_dirty.revision + 1"
            ),
            {"t": loaded_at, "i": fx.instrument_id},
        )
        c.execute(
            text("UPDATE batch_receipt SET record_count = :n, accepted = :n WHERE id = :r"),
            {"n": rows, "r": receipt},
        )
    log.info("fixture %s: %d samples loaded", key, rows)
    return {
        "fixture": key,
        "instrument_id": fx.instrument_id,
        "samples": rows,
        "channels": list(keys),
        "window": [fx.start.isoformat(), (fx.end - timedelta(seconds=1)).isoformat()],
    }
